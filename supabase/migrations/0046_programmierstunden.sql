alter table public.ws_features add column if not exists stunden_gemessen numeric(8,2) not null default 0 check (stunden_gemessen >= 0);
alter table public.ws_features add column if not exists verkauf_key text check (verkauf_key is null or verkauf_key ~ '^[a-z0-9_]{1,40}$');
alter table public.ws_auftraege add column if not exists laeuft_seit timestamptz;
alter table public.ws_auftraege add column if not exists laufzeit_min numeric(10,1) not null default 0;

-- Laufzeit messen: Beginn bei Wechsel nach „laeuft“, Ende bei Wechsel weg davon; je Lauf höchstens 8 Stunden (hängengebliebene Läufe)
create or replace function public.ws_auftrag_laufzeit() returns trigger
language plpgsql security definer set search_path = public as $$
declare m numeric;
begin
  if new.stand = 'laeuft' and old.stand is distinct from 'laeuft' then new.laeuft_seit := now(); end if;
  if old.stand = 'laeuft' and new.stand is distinct from 'laeuft' and old.laeuft_seit is not null then
    m := least(480, greatest(0, extract(epoch from (now() - old.laeuft_seit)) / 60));
    new.laufzeit_min := coalesce(old.laufzeit_min, 0) + round(m, 1);
    new.laeuft_seit := null;
    if new.feature_id is not null then
      perform set_config('cs.aufbau_still', 'an', true); -- Messung ist keine Aufbau-Änderung
      update ws_features set stunden_gemessen = stunden_gemessen + round(m / 60, 2) where id = new.feature_id;
      perform set_config('cs.aufbau_still', '', true);
    end if;
  end if;
  return new;
end $$;
drop trigger if exists ws_auftrag_laufzeit on public.ws_auftraege;
create trigger ws_auftrag_laufzeit before update of stand on public.ws_auftraege for each row execute function public.ws_auftrag_laufzeit();
revoke all on function public.ws_auftrag_laufzeit() from public, anon, authenticated;

-- Admin pflegt Schätzung und Zuordnung
create or replace function public.ws_feature_stunden(p_feature text, p_schaetzung numeric, p_verkauf text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.ws_ist_admin() then raise exception 'Nur der Admin ändert Programmierstunden'; end if;
  update ws_features set stunden_schaetzung = p_schaetzung, verkauf_key = nullif(btrim(coalesce(p_verkauf, '')), '') where id = p_feature;
end $$;
revoke all on function public.ws_feature_stunden(text, numeric, text) from public, anon;
grant execute on function public.ws_feature_stunden(text, numeric, text) to authenticated;

