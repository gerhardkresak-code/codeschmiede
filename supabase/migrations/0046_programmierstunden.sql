--   * ws_features.stunden_schaetzung  – geschätzter Aufwand eines Entwicklers (Stunden), Erstschätzung 26.10.2026 aus dem Code-Umfang
--   * ws_features.stunden_gemessen    – echte Werkstatt-Laufzeit der Aufträge dieses Features (Stunden), zählt automatisch mit
--   * ws_features.verkauf_key         – Verkaufs-Feature der Preiskalkulation (Trainer to go: base44/shared/featureCatalog.ts), null = Plattform-Grundlage
--   * ws_auftraege.laeuft_seit / laufzeit_min – Laufzeit je Auftrag (Stand „In Arbeit“)
-- Beide Stunden gehen über „In die App übernehmen“ in src/lib/appStruktur.features.json (stunden = geschätzt + gemessen, verkauf)
-- und von dort in die ERP-Kalkulation (Pakete & Preise › Kalkulation › „Programmierstunden aus der Codeschmiede“). Mehrfach ausführbar.
