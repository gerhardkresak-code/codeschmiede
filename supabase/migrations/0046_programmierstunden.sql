language plpgsql security definer set search_path = public as $$
declare p text;
begin
  if coalesce(current_setting('cs.aufbau_still', true), '') = 'an' then return new; end if;
  if (new.stunden_schaetzung, new.verkauf_key) is not distinct from (old.stunden_schaetzung, old.verkauf_key) then return new; end if;
  p := (select b.projekt_id from ws_gruppen g join ws_bereiche b on b.id = g.bereich_id where g.id = new.gruppe_id);
  if p is null or (select aufbau_datei from ws_projekte where id = p) is null then return new; end if;
  insert into ws_aufbau_aenderungen (projekt_id, art, text, details) values (p, 'feature_daten', 'Feature ' || new.id || ' „' || new.name || '“: Programmierstunden/Verkaufs-Feature', jsonb_build_object('feature', new.id));
  return new;
end $$;
